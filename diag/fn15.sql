SELECT count(*) AS total FROM wanted;
\echo '=== RPCs do frontend que NAO existem no canonico ==='
SELECT w.name AS missing FROM wanted w
WHERE NOT EXISTS (
  SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
  WHERE n.nspname='public' AND p.proname=w.name)
ORDER BY 1;
\echo '=== erros estaticos plpgsql_check nas RPCs do frontend ==='
SELECT p.proname, p.oid::regprocedure::text AS sig, e.lineno, e.position, e.state, e.message
FROM pg_proc p
JOIN pg_namespace n ON n.oid=p.pronamespace
JOIN wanted w ON w.name=p.proname
CROSS JOIN LATERAL plpgsql_check_function_tb(p.oid, fatal_errors => false, other_warnings => false, extra_warnings => false, performance_warnings => false) e
WHERE n.nspname='public' AND e.level='error'
ORDER BY p.proname, e.lineno;
\echo '=== resumo por funcao ==='
SELECT p.proname, count(*) AS erros
FROM pg_proc p
JOIN pg_namespace n ON n.oid=p.pronamespace
JOIN wanted w ON w.name=p.proname
CROSS JOIN LATERAL plpgsql_check_function_tb(p.oid, fatal_errors => false, other_warnings => false, extra_warnings => false, performance_warnings => false) e
WHERE n.nspname='public' AND e.level='error'
GROUP BY 1 ORDER BY 2 DESC, 1;
