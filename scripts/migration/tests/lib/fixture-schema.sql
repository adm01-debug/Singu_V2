-- Mini-schema estilo Supabase para os testes do kit de migração (somente DDL).
-- Aplicado em bancos descartáveis g6_* — nunca em banco real.
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

CREATE SCHEMA IF NOT EXISTS auth;
CREATE SCHEMA IF NOT EXISTS storage;
CREATE SCHEMA IF NOT EXISTS cron;

CREATE TABLE auth.users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text UNIQUE,
  encrypted_password text,
  raw_user_meta_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE auth.identities (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  provider text NOT NULL,
  identity_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  last_sign_in_at timestamptz,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  email text GENERATED ALWAYS AS (lower(identity_data->>'email')) STORED,
  provider_id text NOT NULL,
  UNIQUE (provider, provider_id)
);
CREATE TABLE storage.buckets (id text PRIMARY KEY, name text NOT NULL, public boolean DEFAULT false);
CREATE TABLE storage.objects (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  bucket_id text REFERENCES storage.buckets(id),
  name text NOT NULL
);

-- Stub mínimo do pg_cron (tabela + funções usadas pelos scripts).
CREATE TABLE cron.job (
  jobid bigserial PRIMARY KEY,
  jobname text UNIQUE,
  schedule text NOT NULL,
  command text NOT NULL,
  active boolean NOT NULL DEFAULT true
);
CREATE FUNCTION cron.schedule(p_name text, p_schedule text, p_command text) RETURNS bigint
LANGUAGE sql AS $f$
  INSERT INTO cron.job(jobname, schedule, command) VALUES (p_name, p_schedule, p_command)
  ON CONFLICT (jobname) DO UPDATE SET schedule = EXCLUDED.schedule, command = EXCLUDED.command, active = true
  RETURNING jobid
$f$;
CREATE FUNCTION cron.unschedule(p_jobid bigint) RETURNS boolean
LANGUAGE sql AS $f$ DELETE FROM cron.job WHERE jobid = p_jobid RETURNING true $f$;
CREATE FUNCTION cron.alter_job(job_id bigint, schedule text DEFAULT NULL, command text DEFAULT NULL,
                               database text DEFAULT NULL, username text DEFAULT NULL, active boolean DEFAULT NULL)
RETURNS void LANGUAGE sql AS $f$
  UPDATE cron.job j SET schedule = COALESCE(alter_job.schedule, j.schedule),
                        command  = COALESCE(alter_job.command, j.command),
                        active   = COALESCE(alter_job.active, j.active)
  WHERE j.jobid = job_id
$f$;

CREATE TYPE public.deal_stage AS ENUM ('novo', 'ganho', 'perdido');

CREATE TABLE public.companies (
  id bigserial PRIMARY KEY,
  name text NOT NULL
);
CREATE TABLE public.contacts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id bigint REFERENCES public.companies(id),
  name text NOT NULL,
  notes text,
  meta jsonb
);
CREATE TABLE public.deals (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_id uuid NOT NULL REFERENCES public.contacts(id),
  stage public.deal_stage NOT NULL DEFAULT 'novo',
  amount numeric(12,2)
);
CREATE TABLE public.interactions (
  id bigserial PRIMARY KEY,
  deal_id integer REFERENCES public.deals(id),
  contact_id uuid REFERENCES public.contacts(id),
  body text
);
CREATE TABLE public.whatsapp_messages (id bigserial PRIMARY KEY, contact_id uuid REFERENCES public.contacts(id), body text);
CREATE TABLE public.profiles (id uuid PRIMARY KEY REFERENCES auth.users(id), display_name text);
CREATE TABLE public.user_roles (id serial PRIMARY KEY, user_id uuid REFERENCES auth.users(id), role text NOT NULL);
-- auto-referência
CREATE TABLE public.categories (id serial PRIMARY KEY, parent_id integer REFERENCES public.categories(id), name text);
