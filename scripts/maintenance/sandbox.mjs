import {readFile,mkdir,rename,readlink} from "node:fs/promises";
import path from "node:path";
import {MaintenanceError,fail,exists,run,git} from "./lib.mjs";

export async function networkPrefix(root) {
  let host;
  try {
    host = await readlink("/proc/self/ns/net");
  } catch {
    throw new MaintenanceError(
      "blocked_network_sandbox",
      "Isolamento de rede Linux indisponível",
    );
  }
  const probe = await run(
    [
      "unshare",
      "--user",
      "--map-root-user",
      "--net",
      "--",
      process.execPath,
      "-e",
      'process.stdout.write(require("fs").readlinkSync("/proc/self/ns/net"))',
    ],
    root,
    5000,
  ).catch(() => null);
  if (
    !probe ||
    probe.code !== 0 ||
    probe.output.trim() === host ||
    !probe.output.startsWith("net:[")
  )
    throw new MaintenanceError(
      "blocked_network_sandbox",
      "Não foi possível criar namespace de rede isolado",
    );
  return ["unshare", "--user", "--map-root-user", "--net", "--"];
}

export const environmentFile = (file) =>
  /(^|\/)\.env(?:\.|$)/.test(file) && !/\.(example|sample)$/.test(file);

export async function quarantine(root, jobDir, prefix = []) {
  const tracked = (await git(root, ["ls-files", "-z"], undefined, prefix))
    .split("\0")
    .filter(Boolean);
  const files = tracked.filter(environmentFile),
    saved = [];
  await mkdir(path.join(jobDir, "quarantine"), {
    recursive: true,
    mode: 0o700,
  });
  for (const [i, file] of files.entries()) {
    const from = path.join(root, file),
      to = path.join(jobDir, "quarantine", String(i));
    if (await exists(from)) {
      await rename(from, to);
      saved.push({ from, to });
    }
  }
  return async () => {
    for (const { from, to } of saved.splice(0)) await rename(to, from);
  };
}

export async function allowedSourceFiles(root, config, prefix = []) {
  const modes = (
    await git(
      root,
      ["ls-files", "-s", "-z", "--", ...config.fix.roots],
      undefined,
      prefix,
    )
  )
    .split("\0")
    .filter(Boolean);
  if (modes.some((line) => line.startsWith("120000 ")))
    fail("Symlink em src impede correção autônoma");
  const files = (
    await git(
      root,
      ["ls-files", "-z", "--", ...config.fix.roots],
      undefined,
      prefix,
    )
  )
    .split("\0")
    .filter(Boolean);
  const excluded = [
    "src/integrations/supabase/types.ts",
    ...(config.fix.exclude || []),
  ].map((file) =>
    path.posix.normalize(file.replaceAll("\\", "/")).replace(/\/+$/, ""),
  );
  const allowed = new Set();
  for (const file of files) {
    if (
      environmentFile(file) ||
      /(?:^|\/)(?:__generated__|generated)\//.test(file) ||
      /\.(?:generated|gen)\./.test(file) ||
      excluded.some((name) => file === name || file.startsWith(`${name}/`))
    )
      continue;
    const header = await readFile(path.join(root, file), "utf8");
    if (
      /(?:^|\n)\s*(?:\/\/|\/\*|\*|#|<!--)[^\n]*(?:@generated\b|auto[- ]generated|automatically generated|generated automatically|generated by|generated file|gerad[oa] (?:por|pel[oa]|automaticamente)|arquivo gerado|do not edit|não edite|nao edite)/i.test(
        header,
      )
    )
      continue;
    if (/[\r\n]/.test(file))
      fail(
        "Nome de arquivo com quebra de linha não suportado pelos scans de formatação",
      );
    allowed.add(file);
  }
  return allowed;
}
