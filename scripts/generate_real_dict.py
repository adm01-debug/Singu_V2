"""Dicionário de dados — DETALHE por coluna (seção "Detalhe por coluna" de docs/data-dictionary.md).

Para cada tabela/view do schema: coluna, tipo, nulidade, valor padrão e comentário, lidos direto
do catálogo do banco (pg_catalog) — não depende mais de arquivo colado em /tmp. Fecha com os
valores de cada enum usado. O resumo de uma linha por tabela é a outra seção do mesmo arquivo,
gerada por scripts/generate_data_dictionary.py — cada script só troca a própria seção.

Uso:
  SUPABASE_DB_URL=postgres://... python3 scripts/generate_real_dict.py
  python3 scripts/generate_real_dict.py --check              # CI: sai 1 se o arquivo está defasado
  python3 scripts/generate_real_dict.py --schema public --out /tmp/dicionario.md --data 2026-11-09

Somente leitura: transação READ ONLY com statement_timeout, encerrada com ROLLBACK.
"""

from __future__ import annotations

import sys

import _pgdocs
import _pgdocs_catalogo as catalogo

SCRIPT = "generate_real_dict.py"
SAIDA_PADRAO = "docs/data-dictionary.md"
TITULO = "📖 Dicionário de Dados — SINGU CRM"
SECAO = "detalhe"
SECOES = [("resumo", "generate_data_dictionary.py"), ("detalhe", "generate_real_dict.py")]
IDENTIDADE = {"a": "GENERATED ALWAYS AS IDENTITY", "d": "GENERATED BY DEFAULT AS IDENTITY"}


def padrao_da_coluna(coluna: dict) -> str:
    """Default como o banco aplica: expressão, identidade ou coluna gerada."""
    if coluna["identidade"] in IDENTIDADE:
        return IDENTIDADE[coluna["identidade"]]
    if coluna["gerada"] == "s" and coluna["padrao"]:
        return f"GENERATED ALWAYS AS ({coluna['padrao']}) STORED"
    return coluna["padrao"] or ""


def renderizar(dados: dict, esquema: str, data: str | None = None) -> str:
    linhas = ["## 📑 Detalhe por coluna", "", _pgdocs.linha_gerado(SCRIPT, data)]
    if not dados["relacoes"]:
        linhas.append(f"_Nenhuma tabela ou view encontrada no schema {_pgdocs.md_codigo(esquema)}._")
        return "\n".join(linhas) + "\n"
    for rel in dados["relacoes"]:
        linhas += [f"## 📋 Tabela: {_pgdocs.md_codigo(rel['nome'])}", ""]
        if rel["tipo"] != "r":
            linhas += [f"Tipo: {catalogo.TIPOS_RELACAO[rel['tipo']]}.", ""]
        if (rel["comentario"] or "").strip():
            linhas += [f"> {_pgdocs.md_texto(rel['comentario'])}", ""]
        linhas += ["| Coluna | Tipo | Null | Padrão | Comentário |", "| :--- | :--- | :--- | :--- | :--- |"]
        for col in rel["colunas"]:
            linhas.append(
                f"| {_pgdocs.md_codigo(col['nome'])} | {_pgdocs.md_codigo(col['tipo'])} | "
                f"{'NO' if col['nao_nulo'] else 'YES'} | {_pgdocs.md_codigo(padrao_da_coluna(col))} | "
                f"{_pgdocs.md_texto(col['comentario'])} |")
        linhas.append("")
    if dados["enums"]:
        linhas += ["## 🔤 Enums", "", "| Enum | Valores (na ordem do banco) |", "| :--- | :--- |"]
        for enum in dados["enums"]:
            valores = ", ".join(_pgdocs.md_codigo(v) for v in (enum["valores"] or [])) or "—"
            linhas.append(f"| {_pgdocs.md_codigo(enum['nome'])} | {valores} |")
        linhas.append("")
    return "\n".join(linhas).rstrip("\n") + "\n"


def principal(argv: list[str] | None = None) -> int:
    args = _pgdocs.criar_parser(__doc__, SAIDA_PADRAO).parse_args(argv)
    amb = _pgdocs.ambiente_psql(aplicacao=SCRIPT)
    dados = catalogo.carregar_catalogo(args.schema, amb, args.timeout)
    destino = _pgdocs.destino_de(args)
    existente = destino.read_text(encoding="utf-8") if destino.is_file() else None
    corpo = renderizar(dados, args.schema, args.data)
    documento = _pgdocs.montar_documento(existente, TITULO, SECOES, SECAO, corpo)
    return _pgdocs.publicar(destino, documento, args.check)


if __name__ == "__main__":
    sys.exit(_pgdocs.executar(principal))
